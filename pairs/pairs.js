// Function to find triangular pairs
function findTriangularPairs(tokenPairs) {
  const triangularPairs = [];

  // Iterate through each token pair
  for (let i = 0; i < tokenPairs.length; i++) {
    const pairA = tokenPairs[i];

    // Check if there's a pair where the second token matches pairA's first token
    const pairB = tokenPairs.find((pair) => pair.token0 === pairA.token1);

    if (pairB) {
      // Check if pairB's second token matches pairA's first token
      const pairC = tokenPairs.find(
        (pair) => pair.token0 === pairA.token0 && pair.token1 === pairB.token1
      );

      if (pairC) {
        // Add the triangular pair to the list
        triangularPairs.push({
          // pairA: pairA.pairSymbol,
          // pairB: pairB.pairSymbol,
          // pairC: pairC.pairSymbol,
          token0: pairA.token0,
          token1: pairA.token1,
          token2: pairB.token1,
          token3: pairC.token0,
        });
      }
    }
  }

  return triangularPairs;
}

